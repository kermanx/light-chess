// 自带开发服务：检查边界规则开关，以及斜镜封口的禁止预览、方向切换和落子。
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { createServer } from 'vite'

const vite = await createServer({
  cacheDir: 'node_modules/.vite-enclosure-check',
  server: { host: '127.0.0.1', port: 0, hmr: false },
})
await vite.listen()
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`http://127.0.0.1:${vite.httpServer.address().port}/`)
  assert.equal(await page.locator('.card').count(), 3, '首页只保留三个游戏入口')
  assert.equal(await page.locator('input, select, .count-ctl').count(), 0, '首页不显示设置')
  if (process.env.LOBBY_SCREENSHOT_DIR) {
    await page.screenshot({ path: `${process.env.LOBBY_SCREENSHOT_DIR}/lobby-desktop.png` })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: `${process.env.LOBBY_SCREENSHOT_DIR}/lobby-mobile.png` })
    await page.setViewportSize({ width: 1280, height: 900 })
  }
  await page.getByText('单机对战').click()
  assert.equal(await page.locator('.pub-opt').count(), 0, '单机准备页不显示公开房间选项')
  const boundary = page.getByLabel('边界反射', { exact: false })
  assert(await boundary.isChecked(), '新局默认开启边界反射')
  await boundary.uncheck()
  await page.getByRole('button', { name: '开始对局' }).click()
  assert(!(await boundary.isChecked()), '准备页设置带入单机')
  await boundary.check()
  await boundary.uncheck()
  const status = text => page.locator('.status-note').filter({ hasText: text }).waitFor()
  const position = async (x, y) => {
    const box = await page.locator('svg.board-svg').boundingBox()
    const scale = box.width / (72 + 36 * 28)
    return [box.x + (36 + x * 28) * scale, box.y + (36 + y * 28) * scale]
  }
  const click = async (x, y, button = 'left') => page.mouse.click(...await position(x, y), { button })
  const hover = async (x, y) => page.mouse.move(...await position(x, y))
  const setup = async () => {
    await click(10.5, 12.5)
    await status('选择家的开口')
    await click(11.6, 12.5)
    await status('红方')
    await click(20.5, 16.5)
    await status('选择家的开口')
    await click(19.4, 16.5)
    await status('蓝方回合')
  }
  const blueMirrors = page.locator('svg path[fill="#2f6fed"]')
  const forbiddenPreview = page.locator('svg line[stroke="#b91c1c"][stroke-dasharray="5 4"]')
  await setup()
  assert(await boundary.isDisabled(), '开局后规则锁定')
  await page.reload()
  await status('蓝方回合')
  assert(!(await boundary.isChecked()) && await boundary.isDisabled(), '刷新后保留关闭状态及锁定')
  console.log('ok: 边界开关默认开启，单机可在开局前设置，开局后锁定且刷新保留')
  await click(11.5, 12)
  await status('红方回合')
  await click(25.5, 25)
  await status('蓝方回合')
  await hover(11.5, 12.5)
  await status('不能放')
  await forbiddenPreview.waitFor({ state: 'attached' })
  await click(11.5, 12.5)
  await hover(30.5, 30.5)
  await status('蓝方回合')
  assert.equal(await blueMirrors.count(), 4, '封口斜镜不能落下')
  console.log('ok: 斜镜封口显示禁止预览，点击后不落子、不换回合')

  await hover(11.5, 12.5)
  await page.keyboard.down('Shift')
  await status('蓝方回合')
  assert.equal(await forbiddenPreview.count(), 0, '切换到合法方向后取消禁止预览')
  await click(11.5, 12.5, 'right') // Shift + 右键仍是非法的 /，验证实际方向独立校验
  assert.equal(await blueMirrors.count(), 4, '右键同样校验实际落子的斜镜方向')
  await click(11.5, 12.5)
  await page.keyboard.up('Shift')
  await status('红方回合')
  assert.equal(await blueMirrors.count(), 5, '反向合法斜镜正常落下')
  console.log('ok: Shift 切换预览方向，左右键均按实际方向校验')

  await page.getByText('重新开始', { exact: true }).click()
  await setup()
  await click(11.5, 12.5)
  await status('红方回合')
  await click(25.5, 25)
  await status('蓝方回合')
  await hover(11.5, 12)
  await status('不能放')
  await forbiddenPreview.waitFor({ state: 'attached' })
  await click(11.5, 12)
  await hover(30.5, 30.5)
  await status('蓝方回合')
  assert.equal(await page.locator('[data-edge="h:11:12"]').count(), 0)
  console.log('ok: 先下斜镜、后用边镜封口也被拒绝')

  await page.getByText('重新开始', { exact: true }).click()
  await setup()
  await hover(11, 12.5)
  await status('不能放')
  await forbiddenPreview.waitFor({ state: 'attached' })
  console.log('ok: 自己封住基地开口会形成同色围墙，仍显示禁止预览')
  await click(25.5, 25)
  await status('红方回合')
  await hover(11, 12.5)
  await status('红方回合')
  assert.equal(await forbiddenPreview.count(), 0)
  await page.locator('svg line[stroke="#e84a3c"][stroke-width="2.6"]').waitFor({ state: 'attached' })
  await click(11, 12.5)
  await status('蓝方回合')
  assert.equal(await page.locator('[data-edge="v:11:12"][fill="#e84a3c"]').count(), 1)
  console.log('ok: 对方可以在基地开口预览并放镜，正常轮转回合')
  await page.getByText('重新开始', { exact: true }).click()
  await boundary.check()
  await page.reload()
  await status('蓝方')
  assert(await boundary.isChecked() && await boundary.isEnabled(), '重新开始可改，开启状态也随刷新保存')
  console.log('ok: 重新开始后解锁边界设置，开启状态随刷新保留')

  await click(4.5, 4.5)
  await click(5.6, 4.5)
  await status('红方')
  await click(8.5, 4.5)
  await status('选择家的开口')
  await hover(7.4, 4.5)
  await status('这个开口会让先手在开局立即命中基地')
  await page.locator('[data-unsafe-exit="1"]').waitFor()
  await click(7.4, 4.5)
  assert.equal(await page.locator('svg path[data-edge]').count(), 3, '开口暴露给先手时仍禁止放置')
  await click(9.6, 4.5)
  await status('蓝方回合')
  await click(6, 4.5)
  await status('红方回合')
  assert.equal(await page.locator('.victory-dialog').count(), 0, '同排基地正常开局，先手放镜自救')
  await page.getByText('重新开始', { exact: true }).click()
  await click(4.5, 4.5)
  await click(5.6, 4.5)
  await status('红方')
  await click(4.5, 8.5)
  await hover(4.5, 7.4)
  await status('这个开口会让先手在开局立即命中基地')
  await page.locator('[data-unsafe-exit="1"]').waitFor()
  await click(4.5, 7.4)
  assert.equal(await page.locator('svg path[data-edge]').count(), 3, '非法方向不落下基地镜子')
  await hover(5.6, 8.5)
  assert.equal(await page.locator('[data-unsafe-exit="1"]').count(), 0)
  await click(5.6, 8.5)
  await status('蓝方回合')
  assert.equal(await page.locator('svg path[data-edge]').count(), 6, '同一位置改为安全方向后正常开局')
  console.log('ok: 同排和同列基地可以安全开局，先手可放镜自救；真正的开局秒杀方向仍被拒绝')
  assert.deepEqual(errors, [])
} finally {
  await browser.close()
  await vite.close()
}
